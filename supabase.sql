drop function if exists public.get_all_customers();
create or replace function public.get_all_customers()
returns table(customer_name text,phone text,address text,order_count bigint,last_order_at timestamptz)
language sql security definer set search_path=public
as $$
 select o.customer_name,o.phone,max(o.address) as address,count(*)::bigint,max(o.created_at) as last_order_at
 from public.orders o
 where exists(select 1 from public.admins a where a.user_id=auth.uid())
 group by o.customer_name,o.phone
 order by max(o.created_at) desc;
$$;
grant execute on function public.get_all_customers() to authenticated;
