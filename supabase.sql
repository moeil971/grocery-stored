create extension if not exists pgcrypto;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text default '',
  consumer_price bigint not null check (consumer_price >= 0),
  store_price bigint not null check (store_price >= 0 and store_price <= consumer_price),
  stock integer not null default 0 check (stock >= 0),
  unit text not null default 'عدد',
  image_url text default '',
  is_popular boolean not null default false,
  is_new boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text unique not null,
  customer_name text not null,
  phone text not null,
  address text not null,
  note text default '',
  subtotal bigint not null default 0,
  discount_total bigint not null default 0,
  final_total bigint not null default 0,
  status text not null default 'ثبت شده'
    check(status in ('ثبت شده','تأیید شده','آماده ارسال','در حال ارسال','تحویل شده','لغو شده')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check(quantity > 0),
  unit_price bigint not null,
  consumer_price bigint not null,
  discount_percent integer not null default 0,
  total bigint not null
);

alter table public.products enable row level security;
alter table public.admins enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- محصولات برای همه قابل مشاهده‌اند.
drop policy if exists "public read products" on public.products;
create policy "public read products" on public.products for select using (true);

-- فقط مدیر ثبت‌شده اجازه تغییر محصول دارد.
drop policy if exists "admins manage products" on public.products;
create policy "admins manage products" on public.products for all to authenticated
using (exists(select 1 from public.admins a where a.user_id=auth.uid()))
with check (exists(select 1 from public.admins a where a.user_id=auth.uid()));

drop policy if exists "admins read admins" on public.admins;
create policy "admins read admins" on public.admins for select to authenticated
using (user_id=auth.uid());

drop policy if exists "admins manage orders" on public.orders;
create policy "admins manage orders" on public.orders for all to authenticated
using (exists(select 1 from public.admins a where a.user_id=auth.uid()))
with check (exists(select 1 from public.admins a where a.user_id=auth.uid()));

drop policy if exists "admins read order items" on public.order_items;
create policy "admins read order items" on public.order_items for select to authenticated
using (exists(select 1 from public.admins a where a.user_id=auth.uid()));

-- ساخت شماره سفارش و ثبت سفارش کاملاً سمت دیتابیس:
create or replace function public.create_order(
  customer_name text,
  phone text,
  address text,
  note text default '',
  items jsonb default '[]'::jsonb
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order_id uuid;
  v_order_number text;
  v_subtotal bigint := 0;
  v_final bigint := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
  v_discount bigint;
begin
  if length(trim(customer_name)) < 2 then raise exception 'نام مشتری نامعتبر است'; end if;
  if length(regexp_replace(phone,'[^0-9]','','g')) < 10 then raise exception 'شماره موبایل نامعتبر است'; end if;
  if length(trim(address)) < 5 then raise exception 'آدرس نامعتبر است'; end if;
  if jsonb_array_length(items)=0 then raise exception 'سبد خرید خالی است'; end if;

  for v_item in select * from jsonb_array_elements(items)
  loop
    select * into v_product from public.products
    where id=(v_item->>'product_id')::uuid
    for update;
    if not found then raise exception 'محصول پیدا نشد'; end if;
    v_qty := greatest(0,(v_item->>'quantity')::integer);
    if v_qty < 1 then raise exception 'تعداد محصول نامعتبر است'; end if;
    if v_qty > v_product.stock then raise exception 'stock: موجودی % کافی نیست',v_product.name; end if;
    v_subtotal := v_subtotal + v_product.consumer_price*v_qty;
    v_final := v_final + v_product.store_price*v_qty;
  end loop;

  v_order_number := 'ORD-' || lpad((floor(random()*90000000)+10000000)::bigint::text,8,'0');
  while exists(select 1 from public.orders where order_number=v_order_number) loop
    v_order_number := 'ORD-' || lpad((floor(random()*90000000)+10000000)::bigint::text,8,'0');
  end loop;

  insert into public.orders(order_number,customer_name,phone,address,note,subtotal,discount_total,final_total)
  values(v_order_number,trim(customer_name),regexp_replace(phone,'[^0-9]','','g'),trim(address),coalesce(note,''),v_subtotal,v_subtotal-v_final,v_final)
  returning id into v_order_id;

  for v_item in select * from jsonb_array_elements(items)
  loop
    select * into v_product from public.products where id=(v_item->>'product_id')::uuid for update;
    v_qty := (v_item->>'quantity')::integer;
    update public.products set stock=stock-v_qty,updated_at=now() where id=v_product.id;
    v_discount := case when v_product.consumer_price>0 then round((v_product.consumer_price-v_product.store_price)*100.0/v_product.consumer_price) else 0 end;
    insert into public.order_items(order_id,product_id,product_name,quantity,unit_price,consumer_price,discount_percent,total)
    values(v_order_id,v_product.id,v_product.name,v_qty,v_product.store_price,v_product.consumer_price,v_discount,v_product.store_price*v_qty);
  end loop;

  return jsonb_build_object('order_number',v_order_number,'order_id',v_order_id);
end $$;

create or replace function public.lookup_orders(customer_phone text)
returns table(order_number text,created_at timestamptz,final_total bigint,status text)
language sql
security definer
set search_path=public
as $$
  select o.order_number,o.created_at,o.final_total,o.status
  from public.orders o
  where o.phone=regexp_replace(customer_phone,'[^0-9]','','g')
  order by o.created_at desc
  limit 50;
$$;

create or replace function public.get_order_by_number(p_order_number text)
returns table(
  order_number text,customer_name text,phone text,address text,note text,
  subtotal bigint,discount_total bigint,final_total bigint,status text,created_at timestamptz,items jsonb
)
language sql
security definer
set search_path=public
as $$
  select o.order_number,o.customer_name,o.phone,o.address,o.note,o.subtotal,o.discount_total,o.final_total,o.status,o.created_at,
  coalesce((select jsonb_agg(jsonb_build_object(
    'product_name',i.product_name,'quantity',i.quantity,'unit_price',i.unit_price,
    'store_price',i.unit_price,'consumer_price',i.consumer_price,'discount_percent',i.discount_percent,'total',i.total
  ) order by i.id) from public.order_items i where i.order_id=o.id),'[]'::jsonb)
  from public.orders o where o.order_number=p_order_number limit 1;
$$;

grant execute on function public.create_order(text,text,text,text,jsonb) to anon,authenticated;
grant execute on function public.lookup_orders(text) to anon,authenticated;
grant execute on function public.get_order_by_number(text) to anon,authenticated;

