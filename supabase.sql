drop function if exists public.update_order_status(uuid,text);
create or replace function public.update_order_status(p_order_id uuid,p_status text)
returns boolean
language plpgsql security definer set search_path=public
as $$
declare
  v_order public.orders%rowtype;
  v_item public.order_items%rowtype;
  v_product public.products%rowtype;
begin
  if not exists(select 1 from public.admins a where a.user_id=auth.uid()) then raise exception 'not authorized'; end if;
  if p_status not in ('ثبت شده','در انتظار تأیید','تأیید شده','آماده ارسال','در حال ارسال','تحویل شده','لغو شده') then
    raise exception 'وضعیت سفارش نامعتبر است';
  end if;

  select * into v_order from public.orders where id=p_order_id for update;
  if not found then raise exception 'سفارش پیدا نشد'; end if;

  if p_status='تأیید شده' and v_order.status='در انتظار تأیید' then
    for v_item in select * from public.order_items where order_id=p_order_id order by id
    loop
      if v_item.product_id is null then raise exception 'محصول سفارش دیگر وجود ندارد: %',v_item.product_name; end if;
      select * into v_product from public.products where id=v_item.product_id for update;
      if not found then raise exception 'محصول سفارش دیگر وجود ندارد: %',v_item.product_name; end if;
      if v_product.stock < v_item.quantity then
        raise exception 'موجودی % کافی نیست؛ سفارش تأیید نشد',v_product.name;
      end if;
    end loop;

    for v_item in select * from public.order_items where order_id=p_order_id order by id
    loop
      update public.products set stock=stock-v_item.quantity,updated_at=now() where id=v_item.product_id;
    end loop;
    update public.orders set stock_deducted=true,status='تأیید شده' where id=p_order_id;
    return true;
  end if;

  if p_status='لغو شده' and v_order.stock_deducted then
    for v_item in select * from public.order_items where order_id=p_order_id
    loop
      if v_item.product_id is not null then
        update public.products set stock=stock+v_item.quantity,updated_at=now() where id=v_item.product_id;
      end if;
    end loop;
    update public.orders set stock_deducted=false,status='لغو شده' where id=p_order_id;
    return true;
  end if;

  update public.orders set status=p_status where id=p_order_id;
  return true;
end $$;
grant execute on function public.update_order_status(uuid,text) to authenticated;

drop function if exists public.delete_order_and_restore_stock(uuid);
create or replace function public.delete_order_and_restore_stock(p_order_id uuid)
returns boolean
language plpgsql security definer set search_path=public
as $$
declare
  v_order public.orders%rowtype;
  v_item public.order_items%rowtype;
begin
  if not exists(select 1 from public.admins a where a.user_id=auth.uid()) then raise exception 'not authorized'; end if;
  select * into v_order from public.orders where id=p_order_id for update;
  if not found then raise exception 'سفارش پیدا نشد'; end if;

  if v_order.stock_deducted then
    for v_item in select * from public.order_items where order_id=p_order_id
    loop
      if v_item.product_id is not null then
        update public.products set stock=stock+v_item.quantity,updated_at=now() where id=v_item.product_id;
      end if;
    end loop;
  end if;

  delete from public.orders where id=p_order_id;
  return true;
end $$;
grant execute on function public.delete_order_and_restore_stock(uuid) to authenticated;

-- گزارش مشتریان برای پنل مدیریت؛ بدون نیاز به حساب مشتری
drop function if exists public.get_all_customers();
create or replace function public.get_all_customers()
returns table(customer_name text,phone text,address text,order_count bigint,last_order_at timestamptz)
language sql security definer set search_path=public
as $$
 select o.customer_name,o.phone,max(o.address) as address,count(*)::bigint,max(o.created_at) as last_order_at
 from public.orders o
 where exists(select 1 from public.admins a where a.user_id=auth.uid())
 group by o.customer_name,o.phone
 order by max(o.created_at) desc;
$$;
grant execute on function public.get_all_customers() to authenticated;

-- حذف کامل مشتری توسط مدیر: چون مشتری جدول حساب جداگانه ندارد، مشتری بر اساس شماره موبایل از سفارش‌ها تشکیل می‌شود.
drop function if exists public.delete_customer_by_phone(text);
create or replace function public.delete_customer_by_phone(p_phone text)
returns integer
language plpgsql security definer set search_path=public
as $$
declare
  v_count integer;
  v_order public.orders%rowtype;
  v_item public.order_items%rowtype;
begin
  if not exists(select 1 from public.admins a where a.user_id=auth.uid()) then raise exception 'not authorized'; end if;

  for v_order in select * from public.orders where phone=regexp_replace(p_phone,'[^0-9]','','g') for update
  loop
    if v_order.stock_deducted then
      for v_item in select * from public.order_items where order_id=v_order.id
      loop
        if v_item.product_id is not null then
          update public.products set stock=stock+v_item.quantity,updated_at=now() where id=v_item.product_id;
        end if;
      end loop;
    end if;
  end loop;

  delete from public.orders where phone=regexp_replace(p_phone,'[^0-9]','','g');
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;
grant execute on function public.delete_customer_by_phone(text) to authenticated;
