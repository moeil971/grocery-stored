create extension if not exists pgcrypto;

-- ============ جدول‌های پایه (از قبل موجودند؛ بدون تغییر ساختار) ============
create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text default '',
  consumer_price bigint not null check (consumer_price >= 0),
  store_price bigint not null check (store_price >= 0 and store_price <= consumer_price),
  stock integer not null default 0 check (stock >= 0),
  unit text not null default 'عدد',
  image_url text default '',
  is_popular boolean not null default false,
  is_new boolean not null default true,
  is_visible boolean not null default true,
  store_price_enabled boolean not null default true,
  show_discount_badge boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text unique not null,
  customer_name text not null,
  phone text not null,
  address text not null,
  note text default '',
  subtotal bigint not null default 0,
  discount_total bigint not null default 0,
  final_total bigint not null default 0,
  status text not null default 'ثبت شده'
    check(status in ('ثبت شده','تأیید شده','آماده ارسال','در حال ارسال','تحویل شده','لغو شده')),
  created_at timestamptz not null default now()
);

-- شماره فاکتورهای کوتاه و ساده: ۱۰۲۴۰، ۱۰۲۴۱، ۱۰۲۴۲، ...
create sequence if not exists public.invoice_number_seq start with 10240;

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check(quantity > 0),
  unit_price bigint not null,
  consumer_price bigint not null,
  discount_percent integer not null default 0,
  total bigint not null
);

